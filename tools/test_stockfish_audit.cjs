'use strict';
const assert = require('node:assert/strict');
const {parseInfo, normalizedScore, getArgs, uciFromSan, uciToSan} = require('./audit_stockfish.cjs');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const ctx=vm.createContext({});
vm.runInContext(fs.readFileSync(path.resolve(__dirname,'../js/chess.js'),'utf8'),ctx);
const Chess=vm.runInContext('Chess',ctx);
assert.deepEqual(parseInfo('info depth 13 seldepth 20 score mate 2 pv e2e4 e7e5'), {depth:13,kind:'mate',value:2,bound:false,pv:'e2e4 e7e5'});
assert.equal(parseInfo('bestmove e2e4'),null);
assert.equal(normalizedScore(parseInfo('info depth 12 score cp -123 nodes 123')), -123);
assert.equal(normalizedScore(parseInfo('info depth 12 score mate 4 pv e2e4')),99600);
assert.equal(normalizedScore(parseInfo('info depth 12 score mate -2 pv e2e4')),-99800);
assert.equal(parseInfo('info depth 12 score cp 999 lowerbound').bound,true);
assert.equal(getArgs(['--depth','12','--include','tactic']).depth,12);
assert.throws(()=>getArgs(['--depth','-1']),/depth/);
assert.equal(getArgs(['--report-only']).reportOnly,true);
assert.equal(getArgs(['--mate-depth','21']).mateDepth,21);
const fen='6k1/5ppp/8/8/8/8/5PPP/4R1K1 w - - 0 1';
assert.equal(uciFromSan(Chess,fen,'Re8#'),'e1e8');
assert.equal(uciToSan(Chess,fen,'e1e8'),'Re8#');
console.log('PASS: UCI score parser, options, and local Chess SAN/UCI conversion');
