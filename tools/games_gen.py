def verify_and_build():
    out = []
    print("=" * 68)
    ok_all = True
    for g in GAMES:
        board = chess.Board()
        sans = []
        bad = None
        for i, (san, note) in enumerate(g["moves"]):
            try:
                mv = board.parse_san(san)
            except Exception as e:
                bad = "ply %d '%s': %s" % (i + 1, san, e)
                break
            sans.append(san)
            board.push(mv)
            if san.endswith("#"):
                if not board.is_checkmate():
                    bad = "ply %d '%s': # が付いているがチェックメイトではありません" % (i + 1, san)
                    break
            elif san.endswith("+"):
                if not board.is_check():
                    bad = "ply %d '%s': + が付いているがチェックではありません" % (i + 1, san)
                    break
            elif board.is_check():
                bad = "ply %d '%s': チェックなのに +/# がありません" % (i + 1, san)
                break
        status = "OK "
        if bad:
            status = "NG!"; ok_all = False
        else:
            last = g["moves"][-1][0]
            if last.endswith("#") and not board.is_checkmate():
                status = "NG!(最終手が#だが詰んでいない)"; ok_all = False
            elif last.endswith("#") and board.is_checkmate():
                status = "OK (詰みも確認)"
        print("%s %-22s %2d手 %s" % (status, g["id"], len(g["moves"]), bad or ""))
        if bad:
            continue
        item = {
            "id": g["id"], "title": g["title"],
            "white": g["white"], "black": g["black"],
            "year": g["year"], "event": g["event"], "result": g["result"],
            "opening": g["opening"], "intro": g["intro"], "takeaway": g["takeaway"],
            "moves": [{"san": s, "note": n} for s, n in g["moves"]],
        }
        en = EN.get(g["id"])
        if en:
            if len(en["notes"]) != len(g["moves"]):
                print("NG! %s: 英語ノート数が指し手数と一致しません" % g["id"])
                ok_all = False
            else:
                item["en"] = {
                    "title": en["title"], "white": en["white"], "black": en["black"],
                    "opening": en["opening"], "intro": en["intro"], "takeaway": en["takeaway"],
                    "moves": [{"san": s, "note": n} for (s, _), n in zip(g["moves"], en["notes"])],
                }
        else:
            print("NG! %s: 英語訳がありません" % g["id"])
            ok_all = False
        out.append(item)
    print("=" * 68)
    print("verified %d / %d games" % (len(out), len(GAMES)))
    return out, ok_all


